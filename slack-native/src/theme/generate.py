#!/usr/bin/env python3
"""Writes <out>.h and <out>.m from design/tokens.json: python3 generate.py <tokens.json> <out>.

design/ is private and not part of the source tree, so the generated files are kept in
src/theme and regenerated with `make theme` whenever the tokens change.
"""
import json
import re
import sys

tokens_path, out = sys.argv[1], sys.argv[2]
tokens = json.load(open(tokens_path))
color = tokens["color"]


def camel(name):
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", name) if part)


def parse_color(text):
    """'#rrggbb', '#rrggbbaa', 'rgb(r,g,b)' or 'rgba(r,g,b,a)' at the start of text, as 0xRRGGBBAA."""
    text = text.strip()
    m = re.match(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?\b", text)
    if m:
        return int(m.group(1) + (m.group(2) or "ff"), 16)
    m = re.match(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)", text)
    if m:
        r, g, b = (int(m.group(i)) for i in (1, 2, 3))
        a = round(float(m.group(4)) * 255) if m.group(4) else 255
        return (r << 24) | (g << 16) | (b << 8) | a
    return None


def hexa(value):
    return "0x%08x" % value


def number(text):
    return float(re.match(r"-?[\d.]+", str(text)).group(0))


def fmt(value):
    return ("%g" % value) if value != int(value) else str(int(value))


semantic = {k: parse_color(v) for k, v in color["semantic_dark"].items()}


def resolve(text):
    """A CSS colour, var(--dt_color-<semantic>) or color-mix(in srgb, <colour> N%, transparent)."""
    text = text.strip()
    m = re.match(r"color-mix\(in srgb,\s*(.+?)\s+([\d.]+)%,\s*transparent\)$", text)
    if m:
        base = resolve(m.group(1))
        return (base & 0xFFFFFF00) | round((base & 0xFF) * float(m.group(2)) / 100)
    m = re.match(r"var\(--dt_color-([\w-]+)\)$", text)
    if m:
        return semantic[m.group(1)]
    return parse_color(text)


def split_top_level(text):
    parts, depth, start = [], 0, 0
    for i, ch in enumerate(text):
        depth += ch == "("
        depth -= ch == ")"
        if ch == "," and depth == 0:
            parts.append(text[start:i])
            start = i + 1
    parts.append(text[start:])
    return [p.strip() for p in parts]


def parse_shadow(text):
    shadows = []
    for part in split_top_level(text):
        inset = part.startswith("inset ")
        part = part[6:] if inset else part
        lengths = re.findall(r"^((?:-?[\d.]+(?:px)?\s+){2,4})", part + " ")[0].split()
        colour = resolve(part[len(" ".join(lengths)):].strip())
        x, y, blur, spread = ([number(v) for v in lengths] + [0, 0])[:4]
        shadows.append((x, y, blur, spread, colour, inset))
    return shadows


def gradient_stops(text):
    stops, previous = [], None
    for part in split_top_level(text)[1:]:
        m = re.match(r"(.+?)\s+([\d.]+)%$", part)
        colour, location = m.group(1), float(m.group(2)) / 100
        if colour == "transparent":
            # CSS interpolates premultiplied; Core Animation does not, so fading towards
            # transparent black would darken the middle. The neighbour's colour at alpha 0 does not.
            stops.append((previous & 0xFFFFFF00, location))
        else:
            previous = resolve(colour)
            stops.append((previous, location))
    return stops


h, m = [], []
h.append("// Generated by src/theme/generate.py from design/tokens.json (Slack's dark mode with the")
h.append("// Aubergine theme). Do not edit; run `make theme`. Colours are sRGB 0xRRGGBBAA.")
h.append("#import <QuartzCore/QuartzCore.h>")
h.append("")
h.append("NS_ASSUME_NONNULL_BEGIN")
h.append("")
h.append("typedef uint32_t SNColorToken;")
h.append("typedef struct { SNColorToken color; CGFloat location; } SNGradientStop;")
h.append("/// One CSS box-shadow: offsets, blur and spread in points.")
h.append("typedef struct { CGFloat x, y, blur, spread; SNColorToken color; BOOL inset; } SNShadow;")
h.append("/// A CSS box-shadow list; CSS paints the first one on top.")
h.append("typedef struct { NSUInteger count; SNShadow shadows[2]; } SNShadowStack;")


def colours(title, prefix, items):
    h.append("")
    h.append("#pragma mark %s" % title)
    for name, value in items:
        if value is not None:
            h.append("static const SNColorToken %s%s = %s;" % (prefix, camel(name), hexa(value)))


for family, shades in color["palette_dark"].items():
    colours("Palette: %s" % family, "SNPalette" + camel(family), ((shade, parse_color(v)) for shade, v in shades.items()))
colours("Semantic colours", "SNColor", semantic.items())
colours("Theme colours (Aubergine)", "SN",
        ((name, parse_color(v["value"])) for name, v in color["theme_dark_aubergine"].items()))
colours("Legacy slack-kit colours", "SNLegacy", ((name[3:], parse_color(v)) for name, v in color["legacy_sk_dark"].items()))
measured = {}
for name, value in color.get("measured_live", {}).items():
    # Only plain single colours: "a over b" composites and "a..b" ranges are not one value.
    if " over " in value or ".." in value:
        continue
    measured[name] = parse_color(value)
colours("Measured live (window captures of the official app; composites as seen, within 1-2 per channel)",
        "SNMeasured", measured.items())
overlays = color["interaction_overlays_dark"]
colours("Hover and pressed overlays, composited with 'lighten'", "SNOverlay",
        ((k, parse_color(re.search(r"#[0-9a-f]{8}", overlays[k]).group(0))) for k in ("hover", "pressed")))

background = color["window_background"]
radial, conic = re.match(r"(radial-gradient\(.*\)) over (conic-gradient\(.*\))$", background["dark_gradient"]).groups()
h.append("")
h.append("#pragma mark Window background")
h.append("/// Used when the background gradients are off.")
h.append("static const SNColorToken SNWindowBackgroundFlat = %s;" % hexa(parse_color(background["dark_flat"])))
h.append("/// A conic gradient around the window's centre, starting this many degrees clockwise from the top,")
h.append("/// under a radial gradient (a circle reaching the corners) with these stops.")
h.append("static const CGFloat SNWindowConicStartDegrees = %s;" % fmt(number(re.search(r"from ([\d.]+)deg", conic).group(1))))
for name, text in (("Conic", conic), ("Radial", radial)):
    stops = gradient_stops(text[text.index("(") + 1:-1])
    h.append("static const SNGradientStop SNWindow%sStops[] = {%s};" % (
        name, ", ".join("{%s, %s}" % (hexa(c), fmt(l)) for c, l in stops)))
    h.append("static const NSUInteger SNWindow%sStopCount = %d;" % (name, len(stops)))

font = tokens["font"]
h.append("")
h.append("#pragma mark Type")
for name, value in font["size"].items():
    h.append("static const CGFloat SNFontSize%s = %s;" % (camel(name), fmt(value)))
for name, value in font["weight"].items():
    if isinstance(value, (int, float)):
        h.append("static const CGFloat SNFontWeight%s = %s;" % (camel(name), fmt(value)))
h.append("/// CSS line-height multipliers.")
for name, value in font["leading"].items():
    h.append("static const CGFloat SNLeading%s = %s;" % (camel(name), fmt(value)))
lato = font["faces"]["Slack-Lato"]
h.append("/// Slack-Lato's faces: Lato 2 files bundled under Resources/fonts, by PostScript name.")
h.append("typedef struct { CGFloat weight; BOOL italic; const char *name; } SNFontFace;")
faces = []
for weight, file in lato.items():
    if weight.isdigit():
        style = camel(file.split("-", 1)[1])
        faces.append((weight, "NO", "Lato-" + style))
        faces.append((weight, "YES", "Lato-" + (style + "Italic" if style != "Regular" else "Italic")))
h.append("static const SNFontFace SNLatoFaces[] = {%s};" % ", ".join('{%s, %s, "%s"}' % f for f in faces))
h.append("static const NSUInteger SNLatoFaceCount = %d;" % len(faces))
mono = re.search(r"variable (\d+)-(\d+)", font["faces"]["Slack-Roboto-Mono"])
h.append("/// Slack-Roboto-Mono is Roboto Mono's variable font, weight axis %s-%s." % mono.groups())
h.append("static const CGFloat SNMonoWeightMin = %s, SNMonoWeightMax = %s;" % mono.groups())

h.append("")
h.append("#pragma mark Space")
for name, value in tokens["space"].items():
    h.append("static const CGFloat SNSpace%s = %s;" % (camel(name.replace("-", "_")) if not name[0].isdigit() else name.replace("-", "_"), fmt(number(value))))

h.append("")
h.append("#pragma mark Radii and borders")
for name, value in tokens["radius"].items():
    if isinstance(value, (int, float)):
        h.append("static const CGFloat SNRadius%s = %s;" % (camel(name), fmt(value)))
    elif name == "ia_icon":
        low, share, high = re.match(r"clamp\(([\d.]+)px, min\(([\d.]+)% of size, ([\d.]+)px\)", value).groups()
        h.append("/// Workspace, app and avatar tiles: %s." % value)
        h.append("static inline CGFloat SNRadiusIaIcon(CGFloat size) { return MAX(%s, MIN(size * %s, %s)); }" % (
            low, fmt(float(share) / 100), high))
    else:
        h.append("/// %s" % value)
        h.append("static const CGFloat SNRadius%s = %s;" % (camel(name), fmt(number(value))))
for name, value in tokens["border_width"].items():
    h.append("static const CGFloat SNBorderWidth%s = %s;" % (name, fmt(value)))

h.append("")
h.append("#pragma mark Shadows")
for name, text in tokens["shadow"].items():
    shadows = parse_shadow(text)
    h.append("static const SNShadowStack SNShadow%s = {%d, {%s}};" % (camel(name.replace("2xl", "xxl")), len(shadows), ", ".join(
        "{%s, %s, %s, %s, %s, %s}" % (fmt(x), fmt(y), fmt(b), fmt(s), hexa(c), "YES" if i else "NO") for x, y, b, s, c, i in shadows)))

h.append("")
h.append("#pragma mark Opacity and stacking")
for name, value in tokens["opacity"].items():
    h.append("static const CGFloat SNOpacity%s = %s;" % (name, fmt(value)))
for name, value in tokens["z_index"].items():
    h.append("static const CGFloat SNZIndex%s = %s;" % (camel(name), fmt(value)))

motion = tokens["motion"]
h.append("")
h.append("#pragma mark Motion")
for name, value in motion["duration_ms"].items():
    h.append("static const CFTimeInterval SNDuration%s = %s;" % (name, fmt(value / 1000)))
for name, value in motion["loops"].items():
    h.append("static const CFTimeInterval SNLoop%s = %s;" % (camel(name), fmt(number(value))))
CSS_EASINGS = {"ease": "cubic-bezier(.25,.1,.25,1)", "ease-in": "cubic-bezier(.42,0,1,1)", "ease-out": "cubic-bezier(0,0,.58,1)",
               "ease-in-out": "cubic-bezier(.42,0,.58,1)", "linear": "cubic-bezier(0,0,1,1)"}
easings = dict(motion["easing"])
live = motion.get("live_timings_ms", {})
if live:
    h.append("/// Measured on the official app (tokens.json motion.live_timings_ms): %s." % live.get("note", ""))
for name, value in live.items():
    if isinstance(value, (int, float)):
        h.append("static const CFTimeInterval SNLive%s = %s;" % (camel(name), fmt(value / 1000)))
    elif name.endswith("_easing"):
        easings["live_" + name[:-len("_easing")]] = motion["easing"].get(value) or CSS_EASINGS[value]
m.append("// Generated by src/theme/generate.py from design/tokens.json. Do not edit; run `make theme`.")
m.append('#import "theme/tokens.h"')
for name, value in easings.items():
    points = re.match(r"cubic-bezier\(([^)]*)\)", value).group(1).split(",")
    h.append("/// %s" % value)
    h.append("CAMediaTimingFunction *SNEase%s(void);" % camel(name))
    m.append("")
    m.append("CAMediaTimingFunction *SNEase%s(void) {" % camel(name))
    m.append("    static CAMediaTimingFunction *function;")
    m.append("    static dispatch_once_t once;")
    m.append("    dispatch_once(&once, ^{ function = [CAMediaTimingFunction functionWithControlPoints:%s]; });" %
             " :".join(p.strip() for p in points))
    m.append("    return function;")
    m.append("}")

h.append("")
h.append("NS_ASSUME_NONNULL_END")
open(out + ".h", "w").write("\n".join(h) + "\n")
open(out + ".m", "w").write("\n".join(m) + "\n")
