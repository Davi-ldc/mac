#!/usr/bin/env python3
"""Generates src/render/emojidata.m from iamcal/emoji-data's emoji.json (MIT).

Usage: python3 -I src/render/emojidata.py <emoji.json> <LICENSE> src/render/emojidata.m

The table keeps what the client needs: Slack's short names, the emoji's text, its picker
category and order, and the five same-tone skin variations. Nothing is read at run time.
"""
import json
import sys

CATEGORIES = ["Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink", "Travel & Places",
              "Activities", "Objects", "Symbols", "Flags", "Component"]
TONES = ["1F3FB", "1F3FC", "1F3FD", "1F3FE", "1F3FF"]


def text(unified):
    return "".join(chr(int(part, 16)) for part in unified.split("-"))


def c_string(value):
    out = []
    for byte in value.encode("utf-8"):
        if 32 <= byte < 127 and chr(byte) not in '"\\?':
            out.append(chr(byte))
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def main(source, license_file, target):
    with open(source, encoding="utf-8") as handle:
        emoji = json.load(handle)
    with open(license_file, encoding="utf-8") as handle:
        notice = handle.read().strip().splitlines()
    emoji = [e for e in emoji if e.get("category") in CATEGORIES and e.get("short_names")]
    emoji.sort(key=lambda e: (CATEGORIES.index(e["category"]), e.get("sort_order", 0)))

    rows, names = [], []
    for index, entry in enumerate(emoji):
        skins = "NULL"
        variations = entry.get("skin_variations") or {}
        if variations:
            # Two-person emoji list every pair of tones; the picker and reactions use one tone for both.
            picked = [variations.get(tone) or variations.get(tone + "-" + tone) for tone in TONES]
            if all(picked):
                skins = c_string("|".join(text(v["unified"]) for v in picked))
        rows.append("    {%s, %s, %s, %d}," % (c_string(" ".join(entry["short_names"])), c_string(text(entry["unified"])), skins,
                                                CATEGORIES.index(entry["category"])))
        for name in entry["short_names"]:
            names.append((name, index))
    names.sort(key=lambda pair: pair[0].encode("utf-8"))

    with open(target, "w", encoding="utf-8") as out:
        out.write("// Generated by src/render/emojidata.py from iamcal/emoji-data's emoji.json. Do not edit.\n")
        out.write("// emoji-data is under the MIT License:\n")
        for line in notice:
            out.write(("// " + line).rstrip() + "\n")
        out.write('#import "render/emojidata.h"\n\n')
        out.write("const SNEmojiEntry SNEmojiTable[] = {\n%s\n};\n" % "\n".join(rows))
        out.write("const NSUInteger SNEmojiTableCount = %d;\n\n" % len(rows))
        out.write("const SNEmojiNameEntry SNEmojiNameTable[] = {\n%s\n};\n" %
                  "\n".join("    {%s, %d}," % (c_string(name), index) for name, index in names))
        out.write("const NSUInteger SNEmojiNameTableCount = %d;\n" % len(names))


if __name__ == "__main__":
    main(*sys.argv[1:4])
