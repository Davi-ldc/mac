#!/usr/bin/env python3
"""Generates src/model/timezonedata.m from the official client's static JS (its TimezoneDetector).

Usage: python3 -I src/model/timezonedata.py design/_src/static src/model/timezonedata.m

The client offers its own list of time zones in Preferences, one per locale with the same zones,
and saves only those: its detect() maps the browser's zone to one of them by name, then through
three tables (manual, equivalent, fallback) in that order. The tables are read from detect()
itself, so renamed variables in a new build are found again. Only the languages this app speaks
are kept (ui/prefs offers en-GB, en-US and pt-BR; en-US is the client's default list).
"""
import json
import os
import re
import sys

LOCALES = ["en-GB", "pt-BR"]


def c_string(value):
    out = []
    for byte in value.encode("utf-8"):
        if 32 <= byte < 127 and chr(byte) not in '"\\?':
            out.append(chr(byte))
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def literal(source, start):
    """The JS array or object literal of strings starting at `start`, as Python values."""
    depth, index, parts = 0, start, []
    while True:
        char = source[index]
        if char == '"':
            end = index + 1
            while source[end] != '"':
                end += 2 if source[end] == "\\" else 1
            parts.append(source[index:end + 1])
            index = end + 1
            continue
        # The minifier leaves keys that are identifiers unquoted (EST:"America/New_York").
        bare = re.compile(r"[A-Za-z_$][\w$]*(?=:)").match(source, index)
        if bare:
            parts.append('"%s"' % bare.group(0))
            index = bare.end()
            continue
        depth += char in "[{"
        depth -= char in "]}"
        parts.append(char)
        index += 1
        if depth == 0:
            break
    text = "".join(parts).replace("\\x", "\\u00").replace("\\'", "'")
    return json.loads(text)


def definition(module, name):
    match = re.search(r"[,;]\s*(?:let |var |const )?%s=(?=[\[{])" % re.escape(name), module)
    if not match:
        sys.exit("no definition of %s in the time zone module" % name)
    return literal(module, match.end())


def main(static, target):
    module = None
    for name in sorted(os.listdir(static)):
        if not name.endswith(".js"):
            continue
        with open(os.path.join(static, name), encoding="utf-8", errors="replace") as handle:
            source = handle.read()
        anchor = source.find("TimezoneDetector=class TimezoneDetector")
        if anchor >= 0:
            # The module's code runs from its tables to the window.timezones_* exports.
            begin = source.rfind(":(function(e,t,n){", 0, anchor)
            module = source[begin:source.find("window.get_canonical_timezone", anchor)]
            break
    if module is None:
        sys.exit("no TimezoneDetector in " + static)

    lists = re.search(r"getList\(e\)\{return e&&(\w+)\[e\]\?\1\[e\]:(\w+)\}", module)
    by_locale, default = lists.group(1), lists.group(2)
    tables = []
    for method in ("intl_api_manual", "intl_api_equivalent", "intl_api_fallback"):
        found = re.search(r"if\((\w+)\[n\]\)return t\.zoneId=\1\[n\],t\.method=\"%s\"" % method, module)
        tables.append(definition(module, found.group(1)))

    choices = {None: definition(module, default)}
    for locale in LOCALES:
        match = re.search(r"%s\[\"%s\"\]=(?=\[)" % (re.escape(by_locale), re.escape(locale)), module)
        choices[locale] = literal(module, match.end())
    zones = {zone for _, zone in choices[None]}
    for locale in LOCALES:
        if {zone for _, zone in choices[locale]} != zones:
            sys.exit("the %s list offers other zones than the default one" % locale)

    aliases, seen = [], set()
    for table in tables:
        for name, zone in table.items():
            if name not in seen and name not in zones:
                seen.add(name)
                aliases.append((name, zone))

    with open(target, "w", encoding="utf-8") as out:
        out.write("// Generated by src/model/timezonedata.py from the official client's TimezoneDetector. Do not edit.\n")
        out.write('#import "model/timezonedata.h"\n\n')
        names = []
        for locale, entries in choices.items():
            name = "Choices" + ("".join(part.capitalize() for part in locale.split("-")) if locale else "Default")
            names.append((locale, name, len(entries)))
            out.write("static const SNTimeZoneEntry %s[] = {\n%s\n};\n" % (name, "\n".join(
                "    {%s, %s}," % (c_string(label), c_string(zone)) for label, zone in entries)))
        out.write("const SNTimeZoneList SNTimeZoneLists[] = {\n%s\n};\n" % "\n".join(
            "    {%s, %s, %d}," % (c_string(locale) if locale else "NULL", name, count) for locale, name, count in names))
        out.write("const NSUInteger SNTimeZoneListCount = %d;\n\n" % len(names))
        out.write("const SNTimeZoneAlias SNTimeZoneAliases[] = {\n%s\n};\n" % "\n".join(
            "    {%s, %s}," % (c_string(name), c_string(zone)) for name, zone in aliases))
        out.write("const NSUInteger SNTimeZoneAliasCount = %d;\n" % len(aliases))


if __name__ == "__main__":
    main(*sys.argv[1:3])
