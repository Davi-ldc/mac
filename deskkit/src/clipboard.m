// Owns clipboard history: watching the pasteboard, sealing entries to disk off the main
// thread, retention, and putting entries back on the pasteboard.
#import <CommonCrypto/CommonCrypto.h>
#import <ImageIO/ImageIO.h>

#import "clipboard.h"
#import "crypto.h"
#import "features.h"
#import "support.h"

// Storage limits. An entry goes 90 days after it was last copied, and sooner when the
// history is over 300 MB on disk, oldest first. A copy whose content is over 10 MB is not
// recorded at all: shrinking an image would paste back something other than what was copied.
static const NSTimeInterval kKeepSeconds = 90 * 86400;
static const unsigned long long kMaxHistoryBytes = 300ull << 20;
static const NSUInteger kMaxEntryBytes = 10 << 20;

static const NSUInteger kPreviewLength = 2000;
// Pasteboard TIFFs are uncompressed. Past this size the PNG would rarely be under the entry
// limit anyway, and converting would hold several large copies in memory.
static const NSUInteger kMaxTIFFBytes = 128 << 20;
static const CGFloat kThumbnailPixels = 64;
// An unreadable Keychain is tried again after 30 seconds, then twice as long each time.
static const NSTimeInterval kFirstKeyRetrySeconds = 30, kMaxKeyRetrySeconds = 15 * 60;
static NSString *const kRestoredMarker = @"local.deskkit.restored";

NSNotificationName const DKClipboardHistoryDidLoadNotification = @"DKClipboardHistoryDidLoadNotification";

BOOL DKPasteboardIsPrivate(NSPasteboard *pasteboard) {
    NSSet *types = [NSSet setWithArray:pasteboard.types ?: @[]];
    for (NSString *type in @[ @"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType",
                              @"org.nspasteboard.AutoGeneratedType", @"com.agilebits.onepassword" ])
        if ([types containsObject:type]) return YES;
    return NO;
}

#pragma mark Clip

static NSArray<NSString *> *KindNames(void) { return @[ @"text", @"files", @"image" ]; }

@interface DKClip ()
@property(readwrite) DKClipKind kind;
@property(readwrite, copy) NSString *text;
@property(readwrite) NSDate *date;
@property(readwrite, copy, nullable) NSString *application;
@property(readwrite) NSSize imageSize;
@property(readwrite, copy, nullable) NSData *thumbnail;
/// Names its two files: the sealed content (.data) and the sealed plist of the rest (.meta).
@property(copy) NSString *identifier;
/// SHA-256 of the full content: two copies are the same when this is.
@property(copy) NSData *digest;
/// What its two files take on disk.
@property unsigned long long bytes;
@end

@implementation DKClip

+ (nullable instancetype)clipWithPlist:(NSDictionary *)plist {
    NSUInteger kind = [KindNames() indexOfObject:plist[@"kind"] ?: @""];
    if (![plist[@"id"] isKindOfClass:NSString.class] || ![plist[@"date"] isKindOfClass:NSDate.class] || kind == NSNotFound)
        return nil;
    DKClip *clip = [DKClip new];
    clip.identifier = plist[@"id"];
    clip.kind = (DKClipKind)kind;
    clip.text = plist[@"text"] ?: @"";
    clip.date = plist[@"date"];
    clip.application = plist[@"app"];
    clip.imageSize = NSMakeSize([plist[@"width"] doubleValue], [plist[@"height"] doubleValue]);
    clip.thumbnail = plist[@"thumbnail"];
    clip.digest = plist[@"digest"] ?: [NSData data];
    return clip;
}

- (NSDictionary *)plist {
    NSMutableDictionary *plist = [@{@"id" : _identifier, @"kind" : KindNames()[_kind], @"text" : _text, @"date" : _date,
                                    @"digest" : _digest} mutableCopy];
    plist[@"app"] = _application;
    plist[@"thumbnail"] = _thumbnail;
    if (_kind == DKClipImage) [plist addEntriesFromDictionary:@{@"width" : @(_imageSize.width), @"height" : @(_imageSize.height)}];
    return plist;
}

@end

#pragma mark Images

static NSData *_Nullable EncodePNG(CGImageRef _Nullable image) {
    if (!image) return nil;
    NSMutableData *png = [NSMutableData new];
    CGImageDestinationRef destination = CGImageDestinationCreateWithData((__bridge CFMutableDataRef)png, CFSTR("public.png"), 1, NULL);
    if (!destination) return nil;
    CGImageDestinationAddImage(destination, image, NULL);
    BOOL done = CGImageDestinationFinalize(destination);
    CFRelease(destination);
    return done ? png : nil;
}

/// Fills in the clip's size and thumbnail and returns the image as PNG data, or nil when
/// it is not an image or the PNG is over `limit` bytes. Reads only the header for the size.
static NSData *_Nullable DescribeImage(DKClip *clip, NSData *content, BOOL isPNG, NSUInteger limit) {
    CGImageSourceRef source = CGImageSourceCreateWithData((__bridge CFDataRef)content, NULL);
    if (!source) return nil;
    NSDictionary *properties = CFBridgingRelease(CGImageSourceCopyPropertiesAtIndex(source, 0, NULL));
    clip.imageSize = NSMakeSize([properties[(id)kCGImagePropertyPixelWidth] doubleValue],
                                [properties[(id)kCGImagePropertyPixelHeight] doubleValue]);
    NSDictionary *options = @{(id)kCGImageSourceCreateThumbnailFromImageAlways : @YES,
                              (id)kCGImageSourceCreateThumbnailWithTransform : @YES,
                              (id)kCGImageSourceThumbnailMaxPixelSize : @(kThumbnailPixels)};
    CGImageRef thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, (__bridge CFDictionaryRef)options);
    clip.thumbnail = EncodePNG(thumbnail);
    if (thumbnail) CGImageRelease(thumbnail);
    NSData *png = content;
    if (!isPNG) {
        CGImageRef image = CGImageSourceCreateImageAtIndex(source, 0, NULL);
        png = EncodePNG(image);
        if (image) CGImageRelease(image);
    }
    CFRelease(source);
    return clip.imageSize.width > 0 && png.length && png.length <= limit ? png : nil;
}

static NSData *Digest(NSData *data) {
    NSMutableData *digest = [NSMutableData dataWithLength:CC_SHA256_DIGEST_LENGTH];
    CC_SHA256(data.bytes, (CC_LONG)data.length, digest.mutableBytes);
    return digest;
}

#pragma mark History

@implementation DKClipboardHistory {
    NSURL *_folder;
    NSData *_Nullable (^_readKey)(void);
    /// Set on the main thread once read, together with the entries.
    NSData *_key;
    BOOL _loading;
    NSTimeInterval _keyRetrySeconds;
    NSInteger _changeCount;
    NSTimer *_poll;
    /// Newest first; touched only on the main thread.
    NSMutableArray<DKClip *> *_clips;
    /// Entries that cannot be opened (see -load) as pairs of identifier and bytes on disk.
    NSMutableArray<NSArray *> *_unreadable;
    /// Reading the key, and sealing, reading, writing and deleting files, in the order asked.
    dispatch_queue_t _io;
}

+ (DKClipboardHistory *)shared {
    static DKClipboardHistory *shared;
    if (!shared) {
        NSString *service = @(getenv("DESKKIT_KEYCHAIN_SERVICE") ?: "local.deskkit");
        shared = [[DKClipboardHistory alloc] initWithFolder:DKSupportSubdirectory(@"clips")
                                                        key:^{ return DKKeychainKey(service, @"clipboard"); }];
    }
    return shared;
}

- (instancetype)initWithFolder:(NSURL *)folder key:(NSData *_Nullable (^)(void))readKey {
    if (!(self = [super init])) return nil;
    _folder = folder;
    _readKey = [readKey copy];
    _keyRetrySeconds = kFirstKeyRetrySeconds;
    _byteLimit = kMaxHistoryBytes;
    _entryByteLimit = kMaxEntryBytes;
    _clips = [NSMutableArray new];
    _unreadable = [NSMutableArray new];
    _io = dispatch_queue_create("local.deskkit.clipboard", DISPATCH_QUEUE_SERIAL);
    return self;
}

- (void)start {
    [self load];
    _changeCount = NSPasteboard.generalPasteboard.changeCount;
    // macOS has no notification for pasteboard changes; a slow poll with a wide tolerance
    // lets the system batch these wakeups with others.
    _poll = [NSTimer scheduledTimerWithTimeInterval:1.0 target:self selector:@selector(check) userInfo:nil repeats:YES];
    _poll.tolerance = 0.5;
}

#pragma mark Files

- (NSURL *)fileFor:(NSString *)identifier extension:(NSString *)extension {
    return [[_folder URLByAppendingPathComponent:identifier] URLByAppendingPathExtension:extension];
}

/// Returns the bytes written, or 0 when writing failed.
- (NSUInteger)write:(NSData *)plain to:(NSURL *)url {
    NSData *sealed = DKEncrypt(plain, _key);
    if (![sealed writeToURL:url options:NSDataWritingAtomic error:nil]) return 0;
    BOOL private = [NSFileManager.defaultManager setAttributes:@{NSFilePosixPermissions : @0600} ofItemAtPath:url.path
                                                         error:nil];
    return private ? sealed.length : 0;
}

- (NSUInteger)writeMeta:(NSDictionary *)plist {
    NSData *meta = [NSPropertyListSerialization dataWithPropertyList:plist format:NSPropertyListBinaryFormat_v1_0
                                                             options:0 error:nil];
    return meta ? [self write:meta to:[self fileFor:plist[@"id"] extension:@"meta"]] : 0;
}

static NSData *_Nullable Unsealed(NSURL *url, NSData *key) {
    NSData *sealed = [NSData dataWithContentsOfURL:url];
    return sealed ? DKDecrypt(sealed, key) : nil;
}

- (void)deleteFilesOf:(NSString *)identifier {
    [NSFileManager.defaultManager removeItemAtURL:[self fileFor:identifier extension:@"meta"] error:nil];
    [NSFileManager.defaultManager removeItemAtURL:[self fileFor:identifier extension:@"data"] error:nil];
}

- (BOOL)isLoaded { return _key != nil; }

- (void)load {
    if (_key || _loading) return;
    _loading = YES;
    // The Keychain can hold its answer back for as long as a prompt stays up, and deskkit's
    // shortcuts live on the main thread.
    dispatch_async(_io, ^{
        NSData *key = self->_readKey();
        NSMutableArray<DKClip *> *clips = [NSMutableArray new];
        NSMutableArray<NSArray *> *unreadable = [NSMutableArray new];
        if (key) [self readEntriesWithKey:key clips:clips unreadable:unreadable];
        dispatch_async(dispatch_get_main_queue(), ^{
            self->_loading = NO;
            if (key) [self adoptKey:key clips:clips unreadable:unreadable];
            else [self loadAgainLater];
        });
    });
}

- (void)loadAgainLater {
    fprintf(stderr, "deskkit: Keychain key unavailable; clipboard history paused for %.0f s\n", _keyRetrySeconds);
    __weak DKClipboardHistory *weakSelf = self;
    dispatch_after(dispatch_time(DISPATCH_TIME_NOW, (int64_t)(_keyRetrySeconds * NSEC_PER_SEC)),
                   dispatch_get_main_queue(), ^{ [weakSelf load]; });
    _keyRetrySeconds = MIN(_keyRetrySeconds * 2, kMaxKeyRetrySeconds);
}

/// On the file queue: the entries on disk, newest first, and those that cannot be opened.
- (void)readEntriesWithKey:(NSData *)key clips:(NSMutableArray<DKClip *> *)clips unreadable:(NSMutableArray<NSArray *> *)unreadable {
    NSMutableDictionary<NSString *, NSURL *> *metas = [NSMutableDictionary new], *datas = [NSMutableDictionary new];
    unsigned long long (^size)(NSURL *) = ^unsigned long long(NSURL *url) {
        NSNumber *bytes;
        [url getResourceValue:&bytes forKey:NSURLFileSizeKey error:nil];
        return bytes.unsignedLongLongValue;
    };
    for (NSURL *url in [NSFileManager.defaultManager
              contentsOfDirectoryAtURL:_folder
            includingPropertiesForKeys:@[ NSURLContentModificationDateKey, NSURLFileSizeKey ]
                               options:0 error:nil]) {
        NSString *identifier = url.URLByDeletingPathExtension.lastPathComponent;
        if ([url.pathExtension isEqualToString:@"meta"]) metas[identifier] = url;
        if ([url.pathExtension isEqualToString:@"data"]) datas[identifier] = url;
    }
    for (NSString *identifier in metas) {
        NSData *plain = Unsealed(metas[identifier], key);
        id plist = plain ? [NSPropertyListSerialization propertyListWithData:plain options:0 format:NULL error:nil] : nil;
        DKClip *clip = [plist isKindOfClass:NSDictionary.class] ? [DKClip clipWithPlist:plist] : nil;
        unsigned long long bytes = size(metas[identifier]) + (datas[identifier] ? size(datas[identifier]) : 0);
        if (clip && datas[identifier]) {
            clip.bytes = bytes;
            [clips addObject:clip];
            continue;
        }
        // An entry that cannot be opened was sealed with a key the Keychain no longer gives
        // back, or is damaged. It stays in case the key returns, until it would have expired
        // or its room is needed.
        NSDate *modified;
        [metas[identifier] getResourceValue:&modified forKey:NSURLContentModificationDateKey error:nil];
        if (clip || -modified.timeIntervalSinceNow > kKeepSeconds) [self deleteFilesOf:identifier];
        else [unreadable addObject:@[ identifier, @(bytes) ]];
    }
    // Content without an entry is left from a write that never finished.
    for (NSString *identifier in datas)
        if (!metas[identifier]) [NSFileManager.defaultManager removeItemAtURL:datas[identifier] error:nil];
    [clips sortUsingComparator:^NSComparisonResult(DKClip *a, DKClip *b) { return [b.date compare:a.date]; }];
}

- (void)adoptKey:(NSData *)key clips:(NSArray<DKClip *> *)clips unreadable:(NSArray<NSArray *> *)unreadable {
    _key = key;
    [_clips setArray:clips];
    [_unreadable setArray:unreadable];
    for (DKClip *clip in clips) _byteCount += clip.bytes;
    for (NSArray *entry in unreadable) _byteCount += [entry[1] unsignedLongLongValue];
    [self prune];
    [NSNotificationCenter.defaultCenter postNotificationName:DKClipboardHistoryDidLoadNotification object:self];
}

/// Drops expired entries, then entries while the history is over its size limit: those that
/// cannot be opened first, then the oldest. The newest stays, as the entry limit keeps it
/// far below the history's.
- (void)prune {
    while (_clips.count && -_clips.lastObject.date.timeIntervalSinceNow > kKeepSeconds) [self remove:_clips.lastObject];
    while (_byteCount > _byteLimit && _unreadable.count) {
        NSArray *entry = _unreadable.firstObject;
        [_unreadable removeObjectAtIndex:0];
        _byteCount -= [entry[1] unsignedLongLongValue];
        dispatch_async(_io, ^{ [self deleteFilesOf:entry[0]]; });
    }
    while (_byteCount > _byteLimit && _clips.count > 1) [self remove:_clips.lastObject];
}

#pragma mark Capture

- (void)check {
    NSPasteboard *pasteboard = NSPasteboard.generalPasteboard;
    // Without the key a change stays unseen, so that it is recorded when the key comes.
    if (!_key || pasteboard.changeCount == _changeCount) return;
    _changeCount = pasteboard.changeCount;
    [self recordPasteboard:pasteboard];
}

- (void)recordPasteboard:(NSPasteboard *)pasteboard {
    if (!_key || DKPasteboardIsPrivate(pasteboard) || [pasteboard.types containsObject:kRestoredMarker]) return;
    DKClip *clip = [DKClip new];
    clip.identifier = NSUUID.UUID.UUIDString;
    clip.date = NSDate.date;
    // The app in front a moment after the copy is, in practice, the one that copied.
    clip.application = NSWorkspace.sharedWorkspace.frontmostApplication.localizedName;
    NSData *content;
    BOOL isPNG = YES;
    NSArray<NSURL *> *files = [pasteboard readObjectsForClasses:@[ NSURL.class ]
                                                        options:@{NSPasteboardURLReadingFileURLsOnlyKey : @YES}];
    NSString *text = [pasteboard stringForType:NSPasteboardTypeString];
    if (files.count) {
        clip.kind = DKClipFiles;
        clip.text = [[files valueForKey:@"path"] componentsJoinedByString:@"\n"];
        content = [clip.text dataUsingEncoding:NSUTF8StringEncoding];
    } else if (text.length) {
        content = [text dataUsingEncoding:NSUTF8StringEncoding];
        if (content.length > _entryByteLimit) return;
        clip.kind = DKClipText;
        clip.text = text.length > kPreviewLength
                        ? [text substringToIndex:NSMaxRange([text rangeOfComposedCharacterSequenceAtIndex:kPreviewLength - 1])]
                        : text;
    } else {
        clip.kind = DKClipImage;
        clip.text = @"";
        content = [pasteboard dataForType:NSPasteboardTypePNG];
        if (!content) {
            content = [pasteboard dataForType:NSPasteboardTypeTIFF];
            isPNG = NO;
        }
        if (!content || content.length > (isPNG ? _entryByteLimit : kMaxTIFFBytes)) return;
    }
    NSUInteger limit = _entryByteLimit;
    dispatch_async(_io, ^{
        NSData *data = clip.kind == DKClipImage ? DescribeImage(clip, content, isPNG, limit) : content;
        if (!data || data.length > limit) return;
        clip.digest = Digest(data);
        NSUInteger dataBytes = [self write:data to:[self fileFor:clip.identifier extension:@"data"]];
        NSUInteger metaBytes = dataBytes ? [self writeMeta:clip.plist] : 0;
        if (!metaBytes) return [self deleteFilesOf:clip.identifier];
        clip.bytes = dataBytes + metaBytes;
        dispatch_async(dispatch_get_main_queue(), ^{ [self insert:clip]; });
    });
}

- (void)insert:(DKClip *)clip {
    // Copying something again moves it to the top instead of adding a duplicate.
    for (DKClip *old in _clips.copy)
        if (old.kind == clip.kind && [old.digest isEqualToData:clip.digest]) [self remove:old];
    [_clips insertObject:clip atIndex:0];
    _byteCount += clip.bytes;
    [self prune];
}

#pragma mark Reading and changing

- (NSArray<DKClip *> *)clipsMatching:(NSString *)query limit:(NSUInteger)limit {
    NSMutableArray<DKClip *> *found = [NSMutableArray new];
    for (DKClip *clip in _clips) {
        if (found.count >= limit) break;
        if (query.length && (clip.kind == DKClipImage ||
                             [clip.text rangeOfString:query options:NSCaseInsensitiveSearch].location == NSNotFound))
            continue;
        [found addObject:clip];
    }
    return found;
}

- (NSData *)contentOf:(DKClip *)clip {
    return Unsealed([self fileFor:clip.identifier extension:@"data"], _key);
}

- (BOOL)copyToPasteboard:(DKClip *)clip {
    NSData *data = [self contentOf:clip];
    if (!data) return NO;
    NSPasteboard *pasteboard = NSPasteboard.generalPasteboard;
    [pasteboard clearContents];
    if (clip.kind == DKClipImage) {
        [pasteboard setData:data forType:NSPasteboardTypePNG];
    } else {
        NSString *text = [[NSString alloc] initWithData:data encoding:NSUTF8StringEncoding] ?: @"";
        if (clip.kind == DKClipFiles) {
            NSMutableArray<NSURL *> *urls = [NSMutableArray new];
            for (NSString *path in [text componentsSeparatedByString:@"\n"]) [urls addObject:[NSURL fileURLWithPath:path]];
            [pasteboard writeObjects:urls];
        } else {
            [pasteboard setString:text forType:NSPasteboardTypeString];
        }
    }
    [pasteboard setData:[NSData data] forType:kRestoredMarker];
    clip.date = NSDate.date;
    [_clips removeObject:clip];
    [_clips insertObject:clip atIndex:0];
    NSDictionary *plist = clip.plist;
    dispatch_async(_io, ^{ [self writeMeta:plist]; });
    return YES;
}

- (void)remove:(DKClip *)clip {
    if (![_clips containsObject:clip]) return;
    [_clips removeObject:clip];
    _byteCount -= clip.bytes;
    NSString *identifier = clip.identifier;
    dispatch_async(_io, ^{ [self deleteFilesOf:identifier]; });
}

- (void)removeAll {
    for (DKClip *clip in _clips.copy) [self remove:clip];
}

@end

void DKStartClipboardHistory(void) { [DKClipboardHistory.shared start]; }
